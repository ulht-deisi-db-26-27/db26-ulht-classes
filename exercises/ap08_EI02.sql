SELECT * FROM HR.employees e
    CROSS JOIN HR.departments d
    WHERE e.DEPARTMENT_ID = d.DEPARTMENT_ID

SELECT * FROM HR.JOBS

SELECT e.EMPLOYEE_ID,e.LAST_NAME,e.SALARY,e.JOB_ID,j.JOB_id,j.MIN_SALARY,j.MAX_SALARY FROM HR.EMPLOYEES e
    CROSS JOIN HR.JOBS  j
    WHERE e.JOB_ID=j.JOB_ID AND e.SALARY NOT BETWEEN j.MIN_SALARY AND j.MAX_SALARY 

SELECT e.EMPLOYEE_ID,e.LAST_NAME,e.SALARY,e.JOB_ID,j.JOB_id,j.MIN_SALARY,j.MAX_SALARY FROM HR.EMPLOYEES e, HR.JOBS  j
    WHERE e.JOB_ID=j.JOB_ID AND e.SALARY NOT BETWEEN j.MIN_SALARY AND j.MAX_SALARY 


SELECT * FROM HR.employees e
    INNER JOIN HR.departments d
        ON e.DEPARTMENT_ID = d.DEPARTMENT_ID    


SELECT * FROM HR.employees e
    LEFT OUTER JOIN HR.departments d
        ON e.DEPARTMENT_ID = d.DEPARTMENT_ID    
    WHERE d.DEPARTMENT_ID IS NULL

SELECT e.EMPLOYEE_ID,e.LAST_NAME,e.DEPARTMENT_ID,
        (SELECT d.DEPARTMENT_NAME
            FROM HR.departments d
            WHERE d.DEPARTMENT_ID = e.DEPARTMENT_ID) as departamento
    FROM HR.EMPLOYEES e    
